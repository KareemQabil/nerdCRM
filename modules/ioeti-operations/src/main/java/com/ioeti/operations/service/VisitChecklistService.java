package com.ioeti.operations.service;

import com.axelor.apps.base.callable.ControllerCallableTool;
import com.axelor.apps.intervention.db.AnswerValue;
import com.axelor.apps.intervention.db.Intervention;
import com.axelor.apps.intervention.db.InterventionQuestion;
import com.axelor.apps.intervention.db.InterventionType;
import com.axelor.apps.intervention.db.repo.InterventionQuestionRepository;
import com.axelor.apps.intervention.db.repo.InterventionRepository;
import com.axelor.apps.intervention.service.InterventionSurveyGenerator;
import com.axelor.apps.intervention.service.helper.InterventionQuestionHelper;
import com.axelor.inject.Beans;
import com.axelor.meta.MetaFiles;
import com.axelor.meta.db.MetaFile;
import com.axelor.rpc.ActionResponse;
import com.google.inject.persist.Transactional;
import com.ioeti.core.api.ApiException;
import java.io.ByteArrayInputStream;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.math.BigDecimal;
import java.time.LocalDate;
import java.util.Set;

/**
 * The visit checklist (capability map, field visits): the native intervention survey. Its questions come
 * from the visit type's native ranges, generated by the native survey generator; answers are saved through
 * the native repository, which keeps "answered" and conditional questions up to date, and the native
 * finish refuses a visit with required questions unanswered. Answers are given on site: while the visit is
 * under way or paused.
 */
public class VisitChecklistService {

  /** Answer types answered from the platform; "indication" is read-only, advanced monitoring stays native. */
  public static final Set<String> ANSWERABLE = Set.of("list", "text", "date", "measure", "checkbox", "picture", "signature");

  /** Whether the visit's type has a checklist (native ranges). */
  public static boolean hasTemplate(Intervention visit) {
    InterventionType type = visit.getInterventionType();
    if (type == null) return false;
    return type.getAdvancedStartupMonitoringRange() != null
        || (type.getHeaderRangeList() != null && !type.getHeaderRangeList().isEmpty())
        || (type.getEquipmentRangeList() != null && !type.getEquipmentRangeList().isEmpty())
        || (type.getFooterRangeList() != null && !type.getFooterRangeList().isEmpty());
  }

  /**
   * Generates (or brings up to date) the checklist with the native generator, as native planning does. It
   * runs outside the caller's transaction and waits for the native process timeout; a message is returned
   * when the generator did not finish in time or failed.
   */
  public String generate(Intervention visit) {
    // the native generator reads the equipment set, which a visit created from the platform has not set yet
    if (visit.getEquipmentSet() == null) visit.setEquipmentSet(new java.util.HashSet<>());
    InterventionSurveyGenerator generator = Beans.get(InterventionSurveyGenerator.class);
    generator.configure(visit);
    ActionResponse response = new ActionResponse();
    new ControllerCallableTool<Integer>().runInSeparateThread(generator, response);
    // the native tool reports a failure as "info" and a timeout as "notify" in the response's first item
    if (response.getData() instanceof java.util.List<?> items && !items.isEmpty() && items.get(0) instanceof java.util.Map<?, ?> item) {
      Object message = item.get("info") != null ? item.get("info") : item.get("notify");
      return message == null ? null : String.valueOf(message);
    }
    return null;
  }

  /** Allowed only while the visit is under way or paused, and only for an active, answerable question. */
  public static void checkAnswerable(Intervention visit, InterventionQuestion question) {
    int status = visit.getStatusSelect() == null ? 0 : visit.getStatusSelect();
    if (status != InterventionRepository.INTER_STATUS_STARTED && status != InterventionRepository.INTER_STATUS_SUSPENDED) {
      throw new ApiException(422, "STATUS_NOT_ALLOWED", "Checklist answers are given while the visit is under way or paused.", null);
    }
    if (!ANSWERABLE.contains(question.getAnswerTypeSelect())) {
      throw new ApiException(422, "NOT_ANSWERABLE", "This item is not answered from the platform.", null);
    }
    if (!InterventionQuestionHelper.isActive(question)) {
      throw new ApiException(422, "NOT_ACTIVE", "This question does not apply with the answers given so far.", null);
    }
  }

  @Transactional(rollbackOn = {Exception.class})
  public InterventionQuestion answerList(InterventionQuestion question, AnswerValue value) {
    question.setListAnswer(value);
    return save(question);
  }

  @Transactional(rollbackOn = {Exception.class})
  public InterventionQuestion answerText(InterventionQuestion question, String text) {
    question.setTextAnswer(text);
    return save(question);
  }

  @Transactional(rollbackOn = {Exception.class})
  public InterventionQuestion answerDate(InterventionQuestion question, LocalDate date) {
    question.setDateAnswer(date);
    return save(question);
  }

  @Transactional(rollbackOn = {Exception.class})
  public InterventionQuestion answerMeasure(InterventionQuestion question, BigDecimal measure) {
    question.setMeasureAnswer(measure);
    return save(question);
  }

  @Transactional(rollbackOn = {Exception.class})
  public InterventionQuestion answerCheckbox(InterventionQuestion question, Boolean checked) {
    question.setCheckboxAnswer(checked);
    return save(question);
  }

  /** Stores a checked image (photo or signature) as the native answer file; null clears the answer. */
  @Transactional(rollbackOn = {Exception.class})
  public InterventionQuestion answerFile(InterventionQuestion question, String fileName, byte[] bytes) {
    MetaFile file = null;
    if (bytes != null) {
      try {
        file = Beans.get(MetaFiles.class).upload(new ByteArrayInputStream(bytes), fileName);
      } catch (IOException e) {
        throw new UncheckedIOException(e);
      }
    }
    if ("signature".equals(question.getAnswerTypeSelect())) question.setSignatureAnswer(file);
    else question.setPictureAnswer(file);
    return save(question);
  }

  private static InterventionQuestion save(InterventionQuestion question) {
    return Beans.get(InterventionQuestionRepository.class).save(question);
  }
}
